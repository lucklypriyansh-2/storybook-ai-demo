// Generates supabase/seed.sql from src/data/templates.json (single source of truth for templates).
import { readFileSync, writeFileSync } from 'node:fs';
const T = JSON.parse(readFileSync(new URL('../src/data/templates.json', import.meta.url)));
const q = s => `'${String(s).replace(/'/g, "''")}'`;
const j = o => `${q(JSON.stringify(o))}::jsonb`;
const rows = T.map(t => `  (${q(t.id)}, ${q(t.title)}, ${q(t.mode)}, ${t.duration_s}, ${j([{ image: t.cover }])}, ${j(t.script)}, ${q(t.cover)}, ${q(t.book_title)}, ${j(t.default_state)}, ${q(t.cliffhanger)}, ${t.sort}, ${q(t.video)})`).join(',\n');
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), `-- Generated by scripts/gen-seed.mjs from src/data/templates.json. Do not edit by hand.
insert into public.templates (id, title, mode, duration_s, scenes, script, cover, book_title, default_state, cliffhanger, sort, video) values
${rows}
on conflict (id) do update set title = excluded.title, mode = excluded.mode, duration_s = excluded.duration_s, scenes = excluded.scenes, script = excluded.script,
  cover = excluded.cover, book_title = excluded.book_title, default_state = excluded.default_state, cliffhanger = excluded.cliffhanger, sort = excluded.sort, video = excluded.video;
`);
console.log('wrote supabase/seed.sql', T.length, 'templates');
